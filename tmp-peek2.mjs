import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage()
page.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE:', m.text().slice(0, 300)) })
page.on('response', (r) => { if (r.status() >= 400) console.log('HTTP', r.status(), r.url().slice(0, 120)) })
await page.goto('http://localhost:3000/login', { waitUntil: 'networkidle' })
await page.fill('input[type="email"]', 'verify-owner-419917@test.local')
await page.fill('input[type="password"]', 'Password123!')
await page.click('button[type="submit"]')
await page.waitForURL('**/dashboard**', { timeout: 15000 })
await page.goto('http://localhost:3000/dashboard/calendar', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(4000)
console.log('URL now:', page.url())
await browser.close()
